/**
 * Generate `src/modules/menu/items/registry.generated.ts` from the item files
 * under `src/modules/menu/items/**`. The category is the relative folder path
 * and the name is the file basename, so adding a menu element means adding one
 * file and re-running this script.
 *
 * Usage:
 *   node scripts/generate-menu-registry.mjs           # write the file
 *   node scripts/generate-menu-registry.mjs --check   # fail if out of date (CI)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { posix, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const itemsDir = resolve(root, 'src/modules/menu/items');
const outFile = resolve(itemsDir, 'registry.generated.ts');
const NAME_RE = /^[a-z]+$/;

function walk(dir) {
	return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
		const full = resolve(dir, entry.name);
		if (entry.isDirectory()) return walk(full);
		return entry.name.endsWith('.ts') && !entry.name.endsWith('.generated.ts') ? [full] : [];
	});
}

const files = walk(itemsDir).sort();
const entries = [];
for (const file of files) {
	const rel = relative(itemsDir, file).split(sep).join(posix.sep);
	const parts = rel.replace(/\.ts$/, '').split('/');
	const name = parts.at(-1);
	const category = parts.slice(0, -1).join('/');
	if (!category) throw new Error(`Item ${rel} must live in a category folder under items/.`);
	if (!NAME_RE.test(name)) throw new Error(`Item ${rel} name must match /^[a-z]+$/.`);
	const source = readFileSync(file, 'utf8');
	if (!/export\s+default\s/.test(source)) throw new Error(`Item ${rel} must default-export its MenuItemSpec.`);
	entries.push({ importPath: `./${rel.replace(/\.ts$/, '.js')}`, name, category });
}

const imports = entries.map((entry, index) => `import item${index} from '${entry.importPath}';`).join('\n');
const registrations = entries
	.map((entry, index) => `\t{ ...item${index}, name: '${entry.name}', category: '${entry.category}' },`)
	.join('\n');

const content = `// AUTO-GENERATED by scripts/generate-menu-registry.mjs — do not edit by hand.
// Add a file under src/modules/menu/items/{category}/ and run \`pnpm menu:registry\`.
import type { MenuItem } from '../MenuItem.js';
${imports}

export const MENU_ITEMS: readonly MenuItem[] = [
${registrations}
];
`;

if (process.argv.includes('--check')) {
	let current = '';
	try {
		current = readFileSync(outFile, 'utf8');
	} catch {
		console.error('menu registry is missing; run `pnpm menu:registry`.');
		process.exit(1);
	}
	if (current !== content) {
		console.error('menu registry is out of date; run `pnpm menu:registry`.');
		process.exit(1);
	}
	console.log(`menu registry up to date (${entries.length} items).`);
} else {
	writeFileSync(outFile, content);
	console.log(`wrote ${relative(root, outFile).split(sep).join(posix.sep)} (${entries.length} items).`);
}
